#!/usr/bin/env python3
"""Tests for scripts/check-attribution. Run directly: python3 scripts/test_check_attribution.py"""

import os
import subprocess
import sys
import tempfile
import unittest

SCRIPT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "check-attribution")
KEN = {"GIT_AUTHOR_NAME": "Ken Fox", "GIT_AUTHOR_EMAIL": "fox@xythian.com",
       "GIT_COMMITTER_NAME": "Ken Fox", "GIT_COMMITTER_EMAIL": "fox@xythian.com"}
CLAUDE = {"GIT_AUTHOR_NAME": "Claude", "GIT_AUTHOR_EMAIL": "noreply@anthropic.com"}
TRAILERS = ("feat: x\n\nBody.\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>\n"
            "Claude-Session: https://claude.ai/code/session_01ABC\n")
PR_FOOTER = "Body.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nhttps://claude.ai/code/session_01ABC\n"
PROJECT_HEADER = ("<!-- claude-projects-attribution: {\"github_login\":\"xythian\"} -->\n"
                  "_Requested by **Ken** · [project thread](https://claude.ai/code/project/chan_1?thread=cmsg_1)_\n\nBody.\n")


def read(path):
    with open(path) as f:
        return f.read()


class CheckAttributionTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.dir = self.tmp.name
        self.env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_") and k != "ORDVIK_PLANNING"}
        self.env.update(HOME=self.dir, GIT_CONFIG_NOSYSTEM="1", **KEN)
        self.git("init", "-q", "-b", "master")
        self.commit("base", {})

    def tearDown(self):
        self.tmp.cleanup()

    def git(self, *args, env=None):
        return subprocess.run(["git", *args], cwd=self.dir, env={**self.env, **(env or {})},
                              check=True, capture_output=True, text=True).stdout

    def commit(self, msg, who):
        self.git("commit", "-q", "--allow-empty", "-m", msg, env=who)

    def run_script(self, *args, stdin="", env=None):
        r = subprocess.run([sys.executable, SCRIPT, *args], cwd=self.dir, input=stdin,
                           env={**self.env, **(env or {})}, capture_output=True, text=True)
        return r.returncode, r.stdout + r.stderr

    def test_clean_commits_pass(self):
        self.commit("feat: clean", KEN)
        self.assertEqual(self.run_script("commits", "master~1..master")[0], 0)

    def test_claude_author_fails(self):
        self.commit("feat: x", CLAUDE)
        code, out = self.run_script("commits", "master~1..master")
        self.assertEqual(code, 1)
        self.assertIn("author Claude <noreply@anthropic.com>", out)

    def test_trailers_fail(self):
        self.commit(TRAILERS, KEN)
        code, out = self.run_script("commits", "master~1..master")
        self.assertEqual(code, 1)
        self.assertIn("Co-Authored-By", out)
        self.assertIn("Claude-Session", out)

    def test_pr_footer_fails_and_project_header_passes(self):
        self.assertEqual(self.run_script("body", stdin=PR_FOOTER)[0], 1)
        self.assertEqual(self.run_script("body", stdin=PROJECT_HEADER)[0], 0)
        prose = "- fails on a \"Generated with Claude Code\" footer or a Claude-Session trailer.\n"
        self.assertEqual(self.run_script("body", stdin=prose)[0], 0)

    def test_strip_removes_trailers_and_footer(self):
        path = os.path.join(self.dir, "msg")
        with open(path, "w") as f:
            f.write(TRAILERS)
        self.assertEqual(self.run_script("strip", path)[0], 0)
        self.assertEqual(read(path), "feat: x\n\nBody.\n")
        with open(path, "w") as f:
            f.write("feat: y\n\nBody.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n")
        self.run_script("strip", path)
        self.assertEqual(read(path), "feat: y\n\nBody.\n")

    def test_author_check(self):
        self.assertEqual(self.run_script("author")[0], 0)
        self.assertEqual(self.run_script("author", env=CLAUDE)[0], 1)

    def test_hooks_through_git(self):
        hooks = os.path.join(os.path.dirname(SCRIPT), "git-hooks")
        self.git("config", "core.hooksPath", hooks)
        os.makedirs(os.path.join(self.dir, "scripts"))
        os.symlink(SCRIPT, os.path.join(self.dir, "scripts", "check-attribution"))
        self.commit(TRAILERS, KEN)
        self.assertEqual(self.git("log", "-1", "--format=%B").strip(), "feat: x\n\nBody.")
        with self.assertRaises(subprocess.CalledProcessError):
            self.commit("feat: z", CLAUDE)

    def test_public_rejects_planning(self):
        msg = "feat: x\n\nSee projects/home/dispatch/20261025-x.md.\n\nDispatch: home/20261025-x done\n"
        self.commit(msg, KEN)
        self.assertEqual(self.run_script("commits", "master~1..master")[0], 0)
        code, out = self.run_script("--public", "commits", "master~1..master")
        self.assertEqual(code, 1)
        self.assertIn("Dispatch: home/20261025-x done", out)
        self.assertIn("projects/home/dispatch/", out)
        self.assertIn("private planning", out)

    def test_public_body(self):
        self.assertEqual(self.run_script("body", stdin=PROJECT_HEADER)[0], 0)
        code, out = self.run_script("--public", "body", stdin=PROJECT_HEADER)
        self.assertEqual(code, 1)
        self.assertIn("claude.ai/code/project/", out)

    def planning(self):
        """A planning checkout: a private project, a project owning a public repo."""
        root = os.path.join(self.dir, "plan")
        files = {
            "planning.yml": "public_deny: ['hush-\\w+']\n",
            "projects/secretmono/project.yml": "project: secretmono\nowns: [acme/secretmono, acme/vault]\n",
            "projects/tool/project.yml": "project: tool\nowns:\n  - {repo: acme/tool, public: true}\n  - acme/tool-infra\n",
        }
        for rel, text in files.items():
            os.makedirs(os.path.dirname(os.path.join(root, rel)), exist_ok=True)
            with open(os.path.join(root, rel), "w") as f:
                f.write(text)
        subprocess.run(["git", "init", "-q", root], check=True, env=self.env)
        subprocess.run(["git", "-C", root, "remote", "add", "origin", "git@github.com:acme/plans.git"], check=True, env=self.env)
        return {"ORDVIK_PLANNING": root}

    def test_public_names_from_planning(self):
        env = self.planning()
        ok = "Ports the tool's guard to acme/tool.\n"
        self.assertEqual(self.run_script("--public", "body", stdin=ok, env=env)[0], 0)
        for bad in ["Ports the guard from secretmono.\n", "See acme/vault.\n", "Moves acme/tool-infra.\n",
                    "Tracked in acme/plans.\n", "For hush-project.\n"]:
            code, out = self.run_script("--public", "body", stdin=bad, env=env)
            self.assertEqual(code, 1, bad)
            self.assertNotIn(bad.strip(), out)  # the log does not repeat the name
        self.assertEqual(self.run_script("--public", "body", stdin="secretmono\n")[0], 0)  # no checkout

    def test_public_commits_check_added_lines(self):
        env = self.planning()
        with open(os.path.join(self.dir, "notes.md"), "w") as f:
            f.write("copied from secretmono\n")
        self.git("add", "notes.md")
        self.commit("docs: notes", KEN)
        code, out = self.run_script("--public", "commits", "master~1..master", env=env)
        self.assertEqual(code, 1)
        self.assertIn("notes.md: adds a line", out)
        self.assertEqual(self.run_script("--public", "commits", "master~1..master")[0], 0)

    def test_pre_push(self):
        env = self.planning()
        base = self.git("rev-parse", "HEAD").strip()
        self.commit("feat: ok", KEN)
        good = self.git("rev-parse", "HEAD").strip()
        self.commit("feat: for secretmono", KEN)
        bad = self.git("rev-parse", "HEAD").strip()
        zero = "0" * 40
        push = lambda local, remote: f"refs/heads/master {local} refs/heads/master {remote}\n"
        self.assertEqual(self.run_script("--public", "pre-push", stdin=push(good, base), env=env)[0], 0)
        self.assertEqual(self.run_script("--public", "pre-push", stdin=push(bad, good), env=env)[0], 1)
        self.assertEqual(self.run_script("--public", "pre-push", stdin=push(bad, zero), env=env)[0], 1)
        self.assertEqual(self.run_script("--public", "pre-push", stdin=push(zero, bad), env=env)[0], 0)

    def test_public_strip_drops_dispatch_trailer(self):
        path = os.path.join(self.dir, "msg")
        with open(path, "w") as f:
            f.write("feat: x\n\nBody.\n\nDispatch: home/x task 1\n")
        self.assertEqual(self.run_script("--public", "strip", path)[0], 0)
        self.assertEqual(read(path), "feat: x\n\nBody.\n")


if __name__ == "__main__":
    unittest.main()
